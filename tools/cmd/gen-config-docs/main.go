// Command gen-config-docs renders docs/configuration.md from the tags on config.Config.
//
//	go run ./tools/cmd/gen-config-docs > docs/configuration.md
package main

import (
	"fmt"
	"os"
	"reflect"
	"strings"

	"github.com/bjornnorgaard/golden-path-go/internal/config"
)

func main() {
	var b strings.Builder
	b.WriteString("<!-- Code generated by tools/cmd/gen-config-docs. DO NOT EDIT. -->\n\n")
	b.WriteString("# Configuration\n\nAll configuration is read from environment variables at startup.\n\n")
	b.WriteString("| Variable | Type | Default | Required | Secret | Description |\n| --- | --- | --- | --- | --- | --- |\n")
	t := reflect.TypeFor[config.Config]()
	for f := range t.Fields() {
		name, opts, _ := strings.Cut(f.Tag.Get("env"), ",")
		required := strings.Contains(opts, "required")
		def := f.Tag.Get("envDefault")
		if def == "" {
			def = "—"
		} else {
			def = "`" + def + "`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n",
			name, f.Type, def, yesNo(required), yesNo(f.Tag.Get("secret") == "true"), f.Tag.Get("doc"))
	}
	if _, err := os.Stdout.WriteString(b.String()); err != nil {
		os.Exit(1)
	}
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}
